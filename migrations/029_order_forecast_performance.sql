-- =============================================================================
-- 029_order_forecast_performance.sql
-- 予想注文ページの高速化
-- =============================================================================
-- 背景:
--   予想注文は hourly_sales の生データ（ぎょうざ系のみで月1.7万行超）を
--   1000行ずつページネーションで取得しており、statement timeout (57014) が
--   頻発していた。アプリ側は daily_gyoza_quantity ビュー（migration 028）の
--   日次集計に切り替える。本マイグレーションはそのビューの集計を高速化する
--   ため product_group 先頭の複合インデックスを追加する
--   （既存インデックスはすべて date / segment 先頭で、ぎょうざ系のみへの
--   絞り込みに効かない）。
-- =============================================================================

CREATE INDEX IF NOT EXISTS idx_hourly_sales_product_group_date
ON hourly_sales (product_group, date);
